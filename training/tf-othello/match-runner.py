_ALPHA = "abcdefgh"

def coord_to_sgf(m: str) -> str:
    if m.lower() == "pass":
        return ""
    x = _ALPHA.index(m[0].lower())
    y = int(m[1]) - 1
    return f"{_ALPHA[x]}{_ALPHA[y]}"


