@dataclass
class GameResult:
    moves: int
    res_a: str
    res_b: str
    sgf: Path


class Game:
    def __init__(self,
                 black: Engine,
                 white: Engine,
                 no: int,
                 match_id: str,
                 out_dir: Path,
                 soft_restart: bool = False):
        self.B = black
        self.W = white
        self.no = no
        self.mid = match_id
        self.out = out_dir
        self.soft_restart = soft_restart

    def _sgf(self, seq, res_tag):
        parts = [SGF_HEADER, f"PB[{self.B.name}]", f"PW[{self.W.name}]", f"RE[{res_tag}]"]
        for col, mv in seq:
            if mv.lower() == "resign":
                continue
            parts.append(f";{col}[{coord_to_sgf(mv)}]")
        parts.append(SGF_FOOTER)
        return "".join(parts)

    def play(self) -> GameResult:
        # fresh engines
        self.B.restart(self.soft_restart)
        self.W.restart(self.soft_restart)

        history = []  # ("B"|"W", move)
        to_move = "black"
        passes = 0
        moves = 0
        discs = 4
        resigned = False

        while True:
            eng = self.B if to_move == "black" else self.W
            opp = self.W if to_move == "black" else self.B

            mv = eng.genmove(to_move).lower()
            if mv.startswith("wrong"):
                break
            moves += 1
            # print(f"[{to_move} {mv}]")
            history.append(("B" if to_move == "black" else "W", mv))
            # print(history)

            # mirror the move to the opponent so its board state matches
            if mv == "pass":
                opp.play_move(to_move, "pass")
            elif mv != "resign":
                opp.play_move(to_move, mv)
                discs += 1
                if discs == 64:
                    break

            if mv == "resign":
                resigned = True
                break
            if mv == "pass":
                passes += 1
                if passes == 2:
                    break
            else:
                passes = 0

            to_move = "white" if to_move == "black" else "black"

        if resigned:
            res_a = res_b = "W+R" if to_move == "black" else "B+R"
        else:
            res_a = self.B.final_score()
            res_b = self.W.final_score()

        if res_a.startswith("unknown"):
            res_a = res_b
        sgf_txt = self._sgf(history, res_a)
        fn = f"{self.mid}_g{self.no:03d}_{self.B.short()}-B_{self.W.short()}-W.sgf"
        fp = self.out / fn
        with open(fp, "w", encoding="utf-8") as f:
            f.write(sgf_txt)

        self.B.close()
        self.W.close()
        return GameResult(moves, res_a, res_b, fp)


